SLOT_RAIL_X = OUTER_HALF_X + 0.62  # 6.02
SLOT_RAIL_R0 = SHELL_R + 0.55  # 22.15, running face
SLOT_RAIL_R1 = SHELL_R + 1.05  # 22.65, back of the rail
ROLLER_R = 0.30
ROLLER_RUN_R = SLOT_RAIL_R0 - ROLLER_R  # 21.85, the roller centre locus
ROLLER_OFFSETS = (-1.9, 0.0, 1.9)
TUBE_PIERCE_S = math.sqrt(SHELL_R**2 - PAYLOAD_R**2)  # 14.620


def roller_radial(station: float) -> float:
    """Radial offset that lands a roller on the rail's running face."""

    return math.sqrt(ROLLER_RUN_R**2 - station**2) - PAYLOAD_R


ROLLER_RADIAL = tuple(roller_radial(TUBE_PIERCE_S + offset)
                      for offset in ROLLER_OFFSETS)  # (1.866, 0.338, -1.599)

# The rib fan has to end short of the roller track. SHELL_R - 0.3 ran 48 ribs
# per lid out to r 21.30, 0.25 m under a roller whose underside is at 21.55.
LID_RIB_R1 = ROLLER_RUN_R - ROLLER_R - SWEPT_CLEARANCE_MIN  # 20.95

# --- sonic baffle case -----------------------------------------------------
# The case is 3.3 m across including its ribs, so it can never pass through
# the shell furniture: it has to BEGIN outboard of it. Hung at radial -1.55
# from station 3.0 it started at chamber radius 13.3 - inside both lid plates,
# through the rib fan, through the 14.6 m girder ring and across both guide
# rails, at every rung. Radial is POSITIVE here so the case hangs where
# tube_radial's docstring says it does (outboard, with the muzzle hinge),
# which also buys 2.5 m of station back.
BAFFLE_RADIAL = 1.55
BAFFLE_LATERAL = 4.55
BAFFLE_HALF_RADIAL = 1.30
BAFFLE_HALF_LATERAL = 1.55
BAFFLE_RIB_HALF_RADIAL = 1.42
BAFFLE_RIB_HALF_LATERAL = 1.66
BAFFLE_RIB_HALF_AXIAL = 0.14
# The aft RIB, not the case, is what has to clear: it is 0.14 m proud behind
# the first station and 0.12 m wider on the inboard flank.
BAFFLE_S0 = math.sqrt(
    (SLOT_RAIL_R1 + SWEPT_CLEARANCE_MIN)**2
    - (PAYLOAD_R + BAFFLE_RADIAL - BAFFLE_RIB_HALF_RADIAL)**2
) + BAFFLE_RIB_HALF_AXIAL  # 16.981
BAFFLE_S1 = 26.0

# --- the swept envelope, and what has to stay out of it --------------------
# Axisymmetric bands of the tube, as (name, station0, station1, radius).
TUBE_ENVELOPE = (
    ("barrel", TUBE_S0 - 0.5, TUBE_S1, TUBE_SWEPT_R),
    ("collar", TUBE_PIERCE_S - 1.32, TUBE_PIERCE_S + 1.15, TUBE_RIB_R + 0.46),
    ("muzzle", TUBE_S1 - 2.4, TUBE_S1 + 0.17, TUBE_RIB_R + 0.55),
)


def tube_local(tilt_deg: float, point) -> tuple[float, float, float]:
    """``point`` in the tube's own (station, radial, lateral) frame."""

    origin = tube_origin(tilt_deg)
    axis = tube_axis(tilt_deg)
    normal = tube_radial(tilt_deg)
    delta = (point[0] - origin[0], point[1] - origin[1], point[2] - origin[2])
    return (
        sum(delta[k] * axis[k] for k in range(3)),
        sum(delta[k] * normal[k] for k in range(3)),
        delta[0],
    )


def _band_distance(station, radial, lateral, s0, s1, radius) -> float:
    radial_gap = math.hypot(radial, lateral) - radius
    station_gap = max(s0 - station, station - s1)
    if radial_gap <= 0.0 and station_gap <= 0.0:
        return max(radial_gap, station_gap)
    return math.hypot(max(radial_gap, 0.0), max(station_gap, 0.0))


def _box_distance(station, radial, lateral, bounds) -> float:
    gaps = [max(low - value, value - high)
            for value, (low, high)
            in zip((station, radial, lateral), bounds)]
    if all(gap <= 0.0 for gap in gaps):
        return max(gaps)
    return math.sqrt(sum(max(gap, 0.0)**2 for gap in gaps))


def tube_clearance(tilt_deg: float, point) -> float:
    """Distance from ``point`` to the tube's solid at ``tilt_deg``.

    Negative means the point is INSIDE the tube. The roller trucks and the
    guide rails they run on are deliberately in contact and are not part of
    this envelope; everything else the tube carries is.
    """

    station, radial, lateral = tube_local(tilt_deg, point)
    distances = [_band_distance(station, radial, lateral, s0, s1, radius)
                 for _, s0, s1, radius in TUBE_ENVELOPE]
    distances.append(_box_distance(station, radial, lateral, (
        (BAFFLE_S0 - BAFFLE_RIB_HALF_AXIAL,
         BAFFLE_S1 + BAFFLE_RIB_HALF_AXIAL),
        (BAFFLE_RADIAL - BAFFLE_RIB_HALF_RADIAL,
         BAFFLE_RADIAL + BAFFLE_RIB_HALF_RADIAL),
        (BAFFLE_LATERAL - BAFFLE_RIB_HALF_LATERAL,
         BAFFLE_LATERAL + BAFFLE_RIB_HALF_LATERAL))))
    # Muzzle hatch as a sphere on its hinge: it swings 104 degrees, so the
    # only pose-independent statement about it is its reach.
    hinge = tube_local(tilt_deg, MUZZLE_PIVOT)
    distances.append(
        math.dist((station, radial, lateral), hinge)
        - (math.hypot(0.30, TUBE_WALL_R) + TUBE_RIB_R + 0.50))
    return min(distances)


def bore_clearance(tilt_deg: float, point) -> float:
    """Distance from ``point`` to the BORE - the volume the car flies down."""

    station, radial, lateral = tube_local(tilt_deg, point)
    return _band_distance(station, radial, lateral,
                          TUBE_S0 - 0.2, TUBE_S1 + 0.1, TUBE_BORE_R)

# ---------------------------------------------------------------------------
# Airlock, tunnel and approach.
#
# The tunnel chord is not a free choice: it is where the deck plane cuts
# the shell. Both radii are solved at DECK_Z so the tunnel is exactly as
# long as the wall is thick there, and the shell segments across that arc
# are omitted rather than boolean-cut (the pack's shell-segment idiom -
# see cut_openings' bevel-after-boolean tombstone in blender_kit).
# ---------------------------------------------------------------------------
TUNNEL_Y_IN = -math.sqrt(CHAMBER_R**2 - TETHER_R**2)  # -11.996
TUNNEL_Y_OUT = -math.sqrt(SHELL_R**2 - TETHER_R**2)  # -13.937
TUNNEL_HALF_X = 3.4
TUNNEL_CLEAR_Z = 5.4  # clear height: an MD-series tanker is ~3.3 m
TUNNEL_TOP_Z = DECK_Z + TUNNEL_CLEAR_Z  # 11.4, the soffit plane

# The tunnel over-runs the shell in Y at both ends so the omitted arc never
# terminates on an open edge. These are the PLUG's extent, and the gate that
# proves the omitted arcs are actually covered has to be able to read them -
# so they live here rather than as literals on build_tunnel's `y_far, y_near`
# line. Margins as authored: the shell arc's far end is at y = -18.530
# (0.870 m of spare), the bore arc's near end at y = -11.996 (0.796 m).
TUNNEL_Y_FAR = -19.4
TUNNEL_Y_NEAR = -11.2

# The omitted arc's LOWER edge is not a free choice either - it is the same
# chord TUNNEL_Y_IN solves for. Put it there and the liner's cut edge, the
# tunnel floor's leading edge and the deck's leading edge all land on the
# one line (TUNNEL_Y_IN, DECK_Z). The first cut authored it by eye as 233.0,
# ONE DEGREE short of the chord, which is not a rounding error at r = 20.4:
# it leaves the bore liner standing 0.21 m proud of the floor straight
# across the mouth, and the cage ring that reuses this window put three
# collision nodes 0.25 m up in the lane. A driven car stopped dead against
# them at the doorway, front axle on the sill, throttle held (live
# 2026-08-24, run 1). Derive it, and it cannot drift again.
def _theta_at_z(z: float, radius: float) -> float:
    """Where a circle of ``radius`` about the hub crosses height ``z``.

    The lower-left branch, theta in (180, 270) - the quadrant the airlock is
    cut into. A point at (radius, theta) is at z = HUB_Z + radius sin theta,
    so wanting sin theta = (z - HUB_Z) / radius with theta past 180 gives
    theta = 180 - asin(...): for z below the hub the asin is negative and
    lands the angle in the third quadrant.
    """

    return 180.0 - math.degrees(math.asin((z - HUB_Z) / radius))


# One arc CANNOT serve two radii. The opening is a rectangle - |x| <=
# TUNNEL_HALF_X, DECK_Z <= z <= TUNNEL_TOP_Z - and a rectangle projects onto
# a DIFFERENT arc on the bore (r = 20.4) than on the shell (r = 21.6). The
# first cut used one authored arc, (207.0, TUNNEL_FLOOR_DEG), for both, and
