# ...and the floor is the ceiling less the bed's own dynamic range. 9.7 dB is
# what the shipped 0.30/0.92 pair was, kept because it is the right SHAPE:
# the ladder's speed range is 182/28 = 6.5x, and a bed that fell by that much
