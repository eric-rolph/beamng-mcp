# ---------------------------------------------------------------------------
# THE CUE SET.
#
# Sixteen mono 48 kHz Ogg cues, procedurally synthesised against this
# machine's own phase edges by authoring/make_spin_launch_audio.py and
# convolved through one chamber impulse response so they share a room. The
# set and every measurement quoted below are in
# authoring/spin_launch_audio_manifest.json; each stop time here is that
# file's published ``recommended_stop_s``, copied so the SHIPPED table is a
# greppable constant rather than a build-time file read.
# tests/test_spin_launch_audio.py compares the two, in both directions.
#
# FOUR ENGINE FACTS THIS IS BUILT ON, all of them expensive to rediscover:
#
# 1. ``AudioDefaultLoop3D`` is the ONLY sound description proven audible on
#    this pipeline (centrifuge audio mechanism v3, after fileName-SFXEmitter
#    and Engine.Audio.playOnce both tested silent/unprovable - AGENTS.md). So
#    there IS no one-shot here: every cue wraps forever unless something
#    stops it. Each one-shot therefore ships with a silent tail pad and its
#    stop lands INSIDE that pad; loops carry stop = None and are stopped by
#    STATE. The generator also ramps every one-shot up from true zero, so
#    that if a stop clock ever fails the cue wraps SILENTLY instead of
#    clicking once per period forever.
# 2. ``obj:createSFXSource`` is an ``obj`` method, independent of the vehicle
#    VM's module stack - which is why it works on a bare proplib prop, and
#    why the audio lives VEHICLE-side while the lights live GE-side (THE
#    PROP CANNOT HOST VEHICLE LIGHT JBEAM PROPS law, AGENTS.md).
# 3. FMOD downmixes 3D sources to mono, so the whole set is authored mono.
#    Nothing is lost and the bytes are halved.
# 4. The stop clocks run on the VEHICLE's graphics dt - the same real clock
#    FMOD plays on - so nothing here is scaled by the GE dtSim ratio.
#
# THE MIX IS DERIVED FROM A LOUDNESS MEASUREMENT, NOT FROM PEAKS, AND NOT
# FROM RMS EITHER.
#
# What shipped: every file peak-normalised to 0.89 and a hand-set vol table
# spanning 6.0 dB, against file RMS values spanning 0.0447 to 0.4552 - a
# 20 dB range the mix knew nothing about. Measured in game at 11.5 m the
# delivered spread was 28.4 dB and it was wrong in four specific ways, each
# of which is a design statement inverted:
#
#   * release_bang landed TENTH of sixteen, 11.3 dB under abort_klaxon. The
#     money moment was the quiet one.
#   * spin_loop buried stage_tick by 26.8 dB - and the ticks fire DURING the
#     ride bed, so the eight console announcements were inaudible in place.
#   * arm_charge (-46.0), clamp_close (-48.0), hard_vacuum (-49.0) and
#     stage_tick (-58.3) all sat under an idling ETK800 (-36.3). hard_vacuum
#     is the cue the design calls "the room audibly stops existing".
#   * and none of it was visible from here, because peak says nothing about
#     loudness and RMS-over-the-whole-file says nothing about whether a
#     transient reads.
#
# So the generator loudness-normalises now (see make_spin_launch_audio.py:
# momentary loudness, the peak of a 400 ms sliding energy window, driven
# toward -7.0 dBFS through a soft limiter capped at 6 dB), publishes the
# achieved figure per cue as ``momentary_dbfs``, and THIS TABLE SOLVES vol
# FROM IT:
#
#     vol = 10 ** ((momentary(release_bang) + rel - momentary(cue)) / 20)
#
# where ``rel`` is the ladder below, in dB relative to release_bang. That
# makes the delivered level a stated design intent instead of an emergent
# property of sixteen synthesis routines, and it makes release_bang the
# loudest thing the machine does BY CONSTRUCTION rather than by hope.
#
# THE LADDER, and why each rung is where it is. Six decibels, top to bottom -
# wide enough to have a foreground and a background, tight enough that
# nothing falls under a car idling next to it (the reviewer measured that
# floor 6.4 dB under the loudest cue).
AUDIO_MIX_LADDER_DB = {
    # SEPARATION. The whole sequence is a crescendo and this is its peak;
    # nothing may out-shout it, and it is the reference the rest is measured
    # against, so it is 0.0 by definition and its vol is exactly 1.00.
    "release_bang": 0.0,
    # YOU ARE SHUT IN - the other structural event in the mod, and the last
    # thing you hear before the world outside stops existing.
    "door_slam": -2.0,
    # An alarm has to be commanding. It is not the throw, and it can never
    # sound at the same time as one: an abort is the phase in which no launch
    # happens.
    "abort_klaxon": -3.0,
    # ANNOUNCEMENTS OVER THE BED. stage_tick fires on top of spin_loop, so
    # its rung is DERIVED from the bed's: 1.5 dB over the bed's ceiling, in
    # its own band (880-3520 Hz against a 55 Hz stack). At any power setting
    # below the top rung the bed is quieter still and the margin grows.
    "stage_tick": -3.5,
    # PAYLOAD DETECTED, and the interlock warble. Both play essentially
    # alone; they used to be the two loudest cues in the mod, above the bang.
    "detect_klaxon": -4.0,
    "release_alarm": -4.0,
    # Beats that must cut THROUGH the ride bed rather than sit under it.
    "muzzle_open": -4.5,
    "shutdown": -4.5,
    "hard_vacuum": -4.5,
    # THE RIDE BED, at its ceiling. The runtime tracks it between
    # AUDIO_SPIN_VOL_FLOOR and this.
    "spin_loop": -5.0,
    "clamp_close": -5.0,
    # The three-second hold. It competes with the player's own idling engine
    # and nothing else, which is the level it is set at.
    "arm_charge": -5.5,
    # BEDS. Machinery you are meant to hear under everything else, and to
    # stop noticing after ten seconds.
    "deck_retract": -6.0,
    "door_travel": -6.0,
    "repress": -6.0,
    "pump_down": -6.0,   # at vac = 1.0; the runtime tracks it down from here
}
assert AUDIO_MIX_LADDER_DB["release_bang"] == 0.0
