# THE TETHER'S WEAVE SCALE, which is a UV question and was answered as a
# texture question.
#
# carbon_weave draws ``tows`` tows across one tile, and a tile is
# ``uv_tile`` METRES, so the tow width on the finished surface is
# uv_tile / tows and NEITHER NUMBER MEANS ANYTHING ALONE. Shipped: tows 16.0
# at uv_tile (1.2, 2.0), i.e. 1.2 / 16 = 75 mm tows. Real prepreg is 5-12 mm
# (3K ~3.5, 12K ~6-7, heavy 24-50K tow ~10-12), so the blade was drawn at
# 6-15x scale and the 2x2 twill read as a course of dark bricks - which is
# exactly what it looks like in the interior shot, on the largest object in
# frame.
#
# WHICH KNOB. Raising tows to 150 gets the same 8 mm at the same tile and is
# the wrong knob, because carbon_weave draws filament striations at
# ``tows * 9`` cycles across ``size`` pixels: 150 tows is 1350 cycles over
# 1024 px = 1.5 px per cycle, well under Nyquist, so the fibre detail folds
# into moire and the fix ships a shimmer. The tile is free of that
# constraint - it does not touch the texture at all - so the TEXTURE IS
# UNCHANGED (16 tows, 144 cycles, 7.1 px per cycle, as shipped and as
# already baked) and only the UVs move.
#
# 10 mm is heavy-tow prepreg, which is what a 16 m structural arm would
# actually be laid up in.
CARBON_TOWS = 16.0
CARBON_TOW_M = 0.010
CARBON_UV_TILE_M = round(CARBON_TOWS * CARBON_TOW_M, 4)  # 0.16 m per tile
assert CARBON_TOWS * 9.0 * 2.0 <= 1024, "carbon_weave filaments alias at this tow count"

