# --- Spin loop automation ---------------------------------------------------
# The console setting is AUDIBLE. pitch = clamp(v / REF, MIN, MAX) where v is
# the live tether speed the gauge shows, so nothing here is a free parameter:
#   REF is the NOMINAL rung, which means the synthesised sample IS what this
#     machine's authored pose sounds like and the pitch is 1.0 there;
#   MAX is the ladder's own top/nominal ratio, 182/82;
#   MIN is HALF the bottom rung's steady ratio (0.3415/2). Not cosmetic:
#     with the floor at 0.3415 a v=28 launch is clamped for its whole 4.40 s
#     ramp and has no crescendo at all. Halving it buys exactly one octave of
#     sweep at the weakest setting. Full range log2(2.2195/0.1707) = 3.700
#     octaves.
AUDIO_SPIN_PITCH_REF = POWER_STEPS_MPS[POWER_NOM_INDEX - 1]  # 82.0
AUDIO_SPIN_PITCH_MAX = round(POWER_STEPS_MPS[-1] / AUDIO_SPIN_PITCH_REF, 4)  # 2.2195
AUDIO_SPIN_PITCH_MIN = round(POWER_STEPS_MPS[0] / AUDIO_SPIN_PITCH_REF / 2.0, 4)  # 0.1707
# The generator brickwalls the loop at (48000/2) / AUDIO_SPIN_PITCH_MAX =
# 10813.2 Hz, rounded DOWN to 10800, because FMOD pitch is a playback-RATE
# change (i.e. resampling) and anything above that folds back as a metallic
# buzz at exactly the moment the machine is loudest. Stated here so the two
# files cannot drift apart silently; the manifest republishes it and
# test_spin_launch_audio compares all three.
SPIN_PARTIAL_CAP_HZ = 10800.0
assert SPIN_PARTIAL_CAP_HZ * AUDIO_SPIN_PITCH_MAX < 24000.0, "spin partials alias"
# Level tracks speed too, so POWER is audible as loudness as well as pitch.
# THE CEILING IS THE TABLE'S OWN FADER, not a second opinion about it: the
# ride bed's rung is AUDIO_MIX_LADDER_DB["spin_loop"], and cueRide walks the
# volume from the floor up to exactly the value the mix table already solved,
# so the bed at full power is the level the ladder says it is. It used to be
# an independently typed 0.92 sitting over a table entry of 0.92 - two copies
# of a number with no mechanism keeping them equal.
