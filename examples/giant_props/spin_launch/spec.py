AUDIO_SPIN_VOL_RANGE_DB = 9.74
AUDIO_SPIN_VOL_FLOOR = round(
    AUDIO_SPIN_VOL_CEIL * 10.0 ** (-AUDIO_SPIN_VOL_RANGE_DB / 20.0), 4)
AUDIO_SPIN_VOL_TOP_MPS = POWER_STEPS_MPS[-1]  # 182.0

# --- Pump bed automation ----------------------------------------------------
# Radiated GAS-borne noise scales with gas density; the pump casing's own
# STRUCTURE-borne noise does not. So the level is a sum, not a ramp, and the
# bed survives hard vacuum at a floor instead of vanishing:
#     vol = STRUCT + GAS * vac   ->  0.55 at vac=1.0, 0.16 at vac=0.0
# Pitch RISES as the chamber empties, because a real vacuum pump unloads and
# speeds up as it pulls down - thin and high is what "nearly there" sounds
# like. A major third, 2^(4/12).
# Derived off the table's fader for the same reason the spin ceiling is: the
# gas-borne term is at full when the chamber is at full, so STRUCT + GAS IS
# the pump bed's rung, and only the SPLIT between them is a free parameter.
# 29 percent structure-borne is what the shipped 0.16/0.55 pair was.
AUDIO_PUMP_VOL_AT_ATMOSPHERE = dict(
    (n, v) for n, _s, v in AUDIO_CUE_TABLE)["pump_down"]
AUDIO_PUMP_STRUCT_FRACTION = 0.29
AUDIO_PUMP_VOL_STRUCT = round(
    AUDIO_PUMP_VOL_AT_ATMOSPHERE * AUDIO_PUMP_STRUCT_FRACTION, 4)
AUDIO_PUMP_VOL_GAS = round(
    AUDIO_PUMP_VOL_AT_ATMOSPHERE - AUDIO_PUMP_VOL_STRUCT, 4)
AUDIO_PUMP_PITCH_LO = 1.0
AUDIO_PUMP_PITCH_HI = round(2.0 ** (4.0 / 12.0), 4)  # 1.2599

# --- Automation push rate ---------------------------------------------------
# The GE side can only ASK the vehicle VM to change a source, and every ask
# is a queueLuaCommand. Checking every frame is free; sending every frame is
# not. So push only on a perceptible RELATIVE pitch step: 1.4% is
# 1200*log2(1.014) = 24.1 cents, right at the just-noticeable difference for
# a slow glide. Worst case is the SHORTEST ramp, v=28:
# ln(0.3415/0.1707)/ln(1.014) = 49.9 pushes over 4.40 s = 11.3/s, a 5x
# reduction against a 60 Hz frame rate. The minimum gap caps that at 12.5/s
# and therefore never actually binds - it is a safety net for a future ramp
# rate, not a live constraint.
AUDIO_PUSH_REL = 0.014
AUDIO_PUSH_MIN_GAP_S = 0.08

# --- The stage-tick ladder --------------------------------------------------
