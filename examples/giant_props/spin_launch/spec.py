SLOT_LEAVES = 30
SLOT_LEAF_OVERLAP = 0.35
SLOT_LEAF_R0 = SHELL_R + 0.10          # 21.700
SLOT_LEAF_STEP = 0.012
SLOT_LEAF_HALF_X = OUTER_HALF_X + 0.10  # 5.50, wider than the shell profile
SLOT_LEAF_R_MAX = SLOT_LEAF_R0 + SLOT_LEAF_STEP * (SLOT_LEAVES - 1)  # 22.048
# The leaves step OUTWARD 12 mm each, so the travelling apron has to clear the
# LAST one, not the first: authored at SHELL_R + 0.22 = 21.820 it was exactly
# coplanar with leaf 10 and buried under leaves 11-29.
APRON_R = SLOT_LEAF_R_MAX + 0.06  # 22.108; five leaf steps proud of the tallest

# Guide rails and the collar's roller trucks. The rollers were authored ON the
# bore axis, which on a STRAIGHT beam riding a CURVED rail puts the three of
# them at three different chamber radii - 20.4, 21.6 and 21.9 - so one missed
