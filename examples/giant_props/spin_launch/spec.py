def _mix_volume(name: str) -> float:
    """Solve one cue's fader from its measured loudness and its rung."""

    rel = AUDIO_MIX_LADDER_DB[name]
    if not AUDIO_MIX_IS_MEASURED:
        # No manifest: the ladder alone, which is the right SHAPE and the
        # wrong absolute level. The gate refuses this state; it exists only
        # so that a checkout without the bank still imports.
        return round(10.0 ** (rel / 20.0), 4)
    reference = _AUDIO_MOMENTARY["release_bang"]
    volume = 10.0 ** ((reference + rel - _AUDIO_MOMENTARY[name]) / 20.0)
    assert volume <= 1.0 + 1e-9, (
        f"{name} needs vol {volume:.3f} to reach its rung: it is "
        f"{reference + rel - _AUDIO_MOMENTARY[name]:+.2f} dB short of the "
        "ladder and the fader has run out of range. Fix the CUE - raise its"
        " momentary loudness in make_spin_launch_audio.py - not this table."
    )
    return round(min(1.0, volume), 4)


