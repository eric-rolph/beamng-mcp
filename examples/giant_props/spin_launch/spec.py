"""Spin Launch Kinetic Accelerator - authored constants for Blender + runtime.

A drivable kinetic launch accelerator, modelled on the suborbital
"spin launch" architecture: a vacuum chamber the size of a stadium roof
standing on edge, a composite tether whipping a payload around inside it,
and a launch tube that lets go of the payload at exactly the moment its
tangent points where you aimed it.

The whole machine is one idea repeated: **the tangent is the trajectory**.
Nothing steers the car after release, so the two knobs on the console are
the only two numbers that matter - how fast the tether is going when it
lets go (POWER) and where on the circle it lets go (ELEVATION). The tube
is not decoration either: it PIVOTS about the chamber axis to stay tangent
to the payload circle at the release angle, so raising the elevation
visibly swings 33 m of launch tube through a 22 m arc over your head. You
can read the setting off the machine from the far end of the ramp.

Sequence (auto, no button press required - the machine notices you):

  1. Drive up the ramp, through the airlock, and park on the cradle.
  2. PAYLOAD DETECTED. Hold still for three seconds.
  3. The blast door drops. The pumps spool and the chamber evacuates.
  4. The load deck sinks away, the cradle clamps close, and the tether
     takes your weight.
  5. Spin-up: escalating plateaus, the velocity needle climbing, the
     tether a blur through the observation ring.
  6. The muzzle hatch opens. On the next pass through the release angle,
     the clamps let go and you leave down the tube.

Anticipation, per the pack's shared design rule: every one of those steps
has its own sound-of-machinery beat, and the longest pause is the one
right before the throw - the muzzle opening while you are already doing
180 m/s and can do nothing about it.

Those beats are AUDIBLE (see AUDIO_CUE_TABLE): sixteen procedurally
synthesised cues on this machine's own phase edges, generated by
authoring/make_spin_launch_audio.py and convolved through one impulse
response derived from this chamber's own Sabine reverberation time, so
they all sound like the same room. Two of them are automated rather than
static, and those two are the ones that earn their keep - the pump bed's
pitch and level track ``b.vac``, so the seven-second evacuation is a
countdown you can hear reach zero, and the spin loop's pitch and level
track ``b.omega``, so the console setting is audible before you can read
the gauge. Both of those beats were silence in every build before this
one, and silence is what made the sequence a progress bar: sound reaches
the player through a sealed blast door when light does not.

The listener is the PAYLOAD, which is the fact the mix is built on. The
emitter is the cage node NAMED by AUDIO_EMITTER_NODE_NAME - the bore
mouth, 20.779 m from the hub in the spin plane and at exactly hub height -
and the player orbits it at PAYLOAD_R. Their distance from it therefore
sweeps 6.12 m to 36.49 m every single revolution, which against
AudioDefaultLoop3D's 20/120 m rolloff is a loudness throb locked to the
spin - 3.568 s per pass at the bottom rung, 0.549 s at the top - free,
correct, and impossible to fake with a static clip.

Frames: authored right-handed, meters, Z-up, +Y is the drive direction, so
the machine is entered from -Y. The chamber's spin axis is authored +X, so
the tether turns in the Y-Z plane and the disc stands on edge facing the
approach. Angles named ``theta`` are measured in that plane from +Y toward
+Z; the tether runs in the direction of DECREASING theta, which is what
puts the release tangent on the +Y side and the airlock out of its way.
"""

