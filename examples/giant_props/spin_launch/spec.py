# ---------------------------------------------------------------------------
# Chamber geometry.
#
# One constraint fixes almost everything else: the payload has to arrive at
# bottom-dead-centre of the tether circle at a height a car can be DRIVEN
# to. DECK_Z is that height, TETHER_R is the visual cradle radius, and
# HUB_Z is forced to their sum. Change either and the load deck stops being
# reachable; the ramp, the tunnel chord and the plinth all key off DECK_Z.
# ---------------------------------------------------------------------------
GROUND_Z = 0.0
# 6.0, and it is not a free choice. BeamNG places a vehicle by its BASE
# ORIGIN - the LOWEST node - and reports ``origin`` from the REF node, so
# nothing may be authored below GROUND_Z or the whole machine is lifted by
# the difference. The lowest thing here is the shell's underside:
#
#     HUB_Z - SHELL_R = DECK_Z + TETHER_R - SHELL_R = DECK_Z - 5.1
#
# so with the plinth standing ON the ground, DECK_Z = (SHELL_R - TETHER_R)
# + t = 5.1 + t, where t is the concrete left under the vessel. t = 0.9 is
# the thickness the plinth already had (shell underside -2.1 over a -3.0
# bottom) - the foundation is not being thinned to buy ramp length, only
# the datum moved. Authored at 3.0 against PLINTH_BOTTOM = -3.0 this prop
# measured origin.z = 3.0 on flat terrain (live 2026-08-24): the approach
# ramp started three metres in the air and could not be driven onto at all.
DECK_Z = 6.0
TETHER_R = 16.5
HUB_Z = DECK_Z + TETHER_R  # 22.5
HUB = (0.0, 0.0, HUB_Z)

# The radius the payload's REFERENCE NODE is held at, which is not the
# cradle deck radius: a car's ref node sits ~0.6 m above the surface it is
# parked on, and the field constrains the ref node, not the tyres. Getting
# this wrong is a visible snap the instant the field engages.
PAYLOAD_R = 15.9

CHAMBER_R = 20.4  # interior bore radius
SHELL_R = 21.6  # outer shell radius (1.2 m wall)
# How far the seven circumferential stiffener flanges stand proud of the
# shell plate. It used to be a literal inside build_chamber's shell profile,
# which was fine while nothing else needed it - but the approach-face signage
# has to clear the flange CROWN rather than the plate, and a standoff derived
# from a number that lives in another file is a standoff that goes stale
# silently. One source; build_chamber reads it too.
SHELL_FLANGE_PROUD = 0.30
HALF_X = 4.2  # interior half-width
OUTER_HALF_X = 5.4  # outer half-width (1.2 m lid plates)
HUB_HOUSING_R = 3.1  # central bearing housing radius

CHAMBER_BOTTOM_Z = HUB_Z - CHAMBER_R  # 2.1, inside the plinth
CHAMBER_TOP_Z = HUB_Z + SHELL_R  # 44.1

# The plinth is what this machine STANDS ON, so its underside IS the
# authored ground plane. It used to be sunk to -3.0 to "bury" the bottom of
# the disc, which is a thing no prop can do: on a flat map the lowest node
# lands on the terrain and everything above it is lifted, so burying the
# plinth is exactly what put the ramp foot 3 m in the air. The top stays
# 0.4 m under the deck - that is what makes the walkable apron read as
# being just below the drive surface, and it swallows the vessel from
# |y| = sqrt(SHELL_R**2 - (HUB_Z - PLINTH_TOP)**2) = 13.452 m inward, well
# inside the plinth's own +/-16.5. Both offsets are unchanged; only the
# datum they hang from moved, so the block is still 5.6 m tall.
PLINTH_BOTTOM = GROUND_Z
PLINTH_TOP = DECK_Z - 0.4  # 5.6

# Tether angles. Bottom-dead-centre is the load position; the tether turns
# toward DECREASING theta.
LOAD_THETA_DEG = 270.0

# ---------------------------------------------------------------------------
# Launch tube.
#
# The tube is TANGENT to the payload circle at the release point, which is
# what makes it a launch tube rather than a pipe bolted to a wall: the
# payload's velocity at release already points exactly down the bore, so
# nothing has to bend the trajectory. Tangency also fixes where the tube
# pierces the shell - acos(PAYLOAD_R / R) further round the rim - and that
# pierce point is what the slot has to be long enough to cover across the
# whole elevation range.
# ---------------------------------------------------------------------------
TILT_STEPS_DEG = (34.0, 39.0, 45.0, 50.0, 56.0, 61.0, 67.0, 72.0)
TILT_NOM_INDEX = 4  # 1-based -> 50 degrees, the authored tube pose
TILT_REF_DEG = TILT_STEPS_DEG[TILT_NOM_INDEX - 1]

# Exit speed per power setting. The tether's angular rate is derived from
# these (omega = v / PAYLOAD_R), never authored directly, so the number on
# the console is the number the car actually leaves with.
POWER_STEPS_MPS = (28.0, 44.0, 62.0, 82.0, 104.0, 128.0, 154.0, 182.0)
POWER_NOM_INDEX = 4  # 82 m/s

TANGENT_OFFSET_DEG = math.degrees(math.acos(PAYLOAD_R / CHAMBER_R))  # 38.79
TANGENT_OFFSET_OUT_DEG = math.degrees(math.acos(PAYLOAD_R / SHELL_R))  # 42.58


def release_theta_deg(tilt_deg: float) -> float:
    """Where on the circle the tangent has the requested elevation.

    Travel is toward decreasing theta, so the tangent at theta is
    (sin theta, -cos theta) in (y, z). Setting that equal to
    (cos a, sin a) - elevation ``a`` above horizontal, pointing +Y -
    gives theta = 90 + a. That identity is the whole aiming system.
    """

    return 90.0 + tilt_deg


def tube_origin(tilt_deg: float) -> tuple[float, float, float]:
    """Release point (the tube's bore axis at s = 0), authored frame."""

    theta = math.radians(release_theta_deg(tilt_deg))
    return (
        0.0,
        PAYLOAD_R * math.cos(theta),
        HUB_Z + PAYLOAD_R * math.sin(theta),
    )


def tube_axis(tilt_deg: float) -> tuple[float, float, float]:
    """Unit vector down the bore, authored frame."""

    theta = math.radians(release_theta_deg(tilt_deg))
    return (0.0, math.sin(theta), -math.cos(theta))


# Bore station range: a short breech length behind the release point (the
# muzzle-loading end, inside the chamber) and 30 m of tube outside it.
TUBE_S0 = -3.5
TUBE_S1 = 30.0
TUBE_BORE_R = 2.55
TUBE_WALL_R = 3.25
TUBE_RIB_R = 3.62
TUBE_SEGMENTS = 11  # flanged barrel sections


def tube_radial(tilt_deg: float) -> tuple[float, float, float]:
    """Outward normal of the payload circle at the release point.

    This is the tube's "up" in its own frame: perpendicular to the bore and
    pointing away from the hub, which is where the muzzle hatch hinges and
    where the baffle case hangs.
    """

    theta = math.radians(release_theta_deg(tilt_deg))
    return (0.0, math.cos(theta), math.sin(theta))


def tube_point(tilt_deg: float, station: float, radial: float = 0.0,
               lateral: float = 0.0) -> tuple[float, float, float]:
    """A point on the tube: ``station`` down the bore, ``radial`` out."""

    origin = tube_origin(tilt_deg)
    axis = tube_axis(tilt_deg)
    normal = tube_radial(tilt_deg)
    return (
        origin[0] + axis[0] * station + normal[0] * radial + lateral,
        origin[1] + axis[1] * station + normal[1] * radial,
        origin[2] + axis[2] * station + normal[2] * radial,
    )


# Muzzle hatch hinge, on the tube's outboard lip. Authored at TILT_REF_DEG
# like the rest of the tube; the runtime carries it round the chamber axis
# with the tube and then swings it about this pivot.
MUZZLE_PIVOT = tube_point(TILT_REF_DEG, TUBE_S1 - 0.25, TUBE_WALL_R)

# ---------------------------------------------------------------------------
# Swept-volume clearance.
#
# The tube is ONE rigid body pivoted about the chamber axis, so the volume it
# occupies across the ladder is the union of eight poses of the same solid -
# and because phi = tilt - TILT_REF_DEG is monotonic in the setting, that
# union is bounded by the two END rungs. Anything clockwise of the tilt-34
# pose, or anticlockwise of the tilt-72 pose, is clear at EVERY rung.
#
# Everything below is solved in the tube's own frame, where a point at
# chamber angle theta and chamber radius rho has radial offset
#
#     r = rho * cos(theta - release_theta) - PAYLOAD_R
#
# independent of station, because the bore axis is a TANGENT to the payload
# circle. Angles here are solved from that identity rather than eyeballed off
# a render - which is exactly how the beacon came to sit 0.115 m off the bore
# axis at tilt 34 while every render, the selector thumbnail and both gates
# sat at 50 degrees, the first rung that clears it.
# ---------------------------------------------------------------------------

# The widest thing on the axisymmetric part of the tube: the flange bolt
# heads, whose circle is TUBE_RIB_R + 0.02 and whose heads are 0.055 across.
TUBE_SWEPT_R = TUBE_RIB_R + 0.02 + 0.055  # 3.695

# One clearance for the whole machine. 0.60 m is wide enough that a 4 cm
# authoring slip cannot close it and tight enough that the slot stays a slot
# rather than a hole in the crown.
SWEPT_CLEARANCE_MIN = 0.60


def swept_radial(tilt_deg: float, theta_deg: float, radius: float) -> float:
    """Radial offset of a chamber point from the bore axis at ``tilt_deg``."""

    return radius * math.cos(
        math.radians(theta_deg - release_theta_deg(tilt_deg))) - PAYLOAD_R


def swept_edge_deg(tilt_deg: float, radius: float, offset: float) -> float:
    """Chamber angle where the bore's ``offset`` flank crosses ``radius``.

    Inverse of ``swept_radial``. A NEGATIVE offset returns the clockwise
    (low-angle) edge and a positive one the anticlockwise edge, so both slot
    jambs come out of the same line of arithmetic.
    """

    return release_theta_deg(tilt_deg) - math.degrees(
        math.acos((PAYLOAD_R + offset) / radius))


# --- shell slot ------------------------------------------------------------
# The slot is sized from the TUBE, not from the pierce angle. The pierce point
# only sweeps 81.4 -> 119.4 degrees, but the barrel is 7.4 m across and nearly
# tangent to the shell there, so its silhouette on the rim is far wider than
# its centreline: at tilt 34 the inboard flank crosses the jamb's outer corner
# at 65.1 degrees, which is why an authored 70.0 left 1.48 m of machined jamb
# standing inside the barrel.
SLOT_JAMB_R = SHELL_R + 0.38  # 21.98, jamb box centre radius
SLOT_JAMB_HALF_R = 0.48
SLOT_JAMB_HALF_T = 0.60
_JAMB_OUT = SLOT_JAMB_R + SLOT_JAMB_HALF_R  # 22.46
_JAMB_IN = SLOT_JAMB_R - SLOT_JAMB_HALF_R  # 21.50
SLOT_DEG = (
    swept_edge_deg(TILT_STEPS_DEG[0],
                   math.hypot(_JAMB_OUT, SLOT_JAMB_HALF_T),
                   -(TUBE_SWEPT_R + SWEPT_CLEARANCE_MIN))
    - math.degrees(math.atan2(SLOT_JAMB_HALF_T, _JAMB_OUT)),
    swept_edge_deg(TILT_STEPS_DEG[-1],
                   math.hypot(_JAMB_IN, SLOT_JAMB_HALF_T),
                   TUBE_SWEPT_R + SWEPT_CLEARANCE_MIN)
    + math.degrees(math.atan2(SLOT_JAMB_HALF_T, _JAMB_IN)),
)  # (63.568, 143.472)

# Shingle leaves. Leaf i runs [start + span*(i - overlap),
# start + span*(i + 1 + overlap)] with span = (end - start) / SLOT_LEAVES,
# which unions to [start - span*overlap, end + span*overlap] - a superset of
